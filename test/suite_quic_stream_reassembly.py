"""QUIC connection tracking and multi-stream reassembly tests.

The three captures are generated by
``tools/generate-quic-stream-reassembly-captures.py`` and checked into
``test/captures``. They contain one synthetic QUIC connection each, with the
same three streams and deterministic payloads:

* ``quic-stream-ordered.pcap``: frames arrive in offset order;
* ``quic-stream-out-of-order.pcap``: later datagrams of client stream 0 are
  reversed;
* ``quic-stream-retrans.pcap``: stream 0 datagrams are replayed and overlap.

``test/keys/quic-stream-reassembly.keys`` contains the matching TLS secrets.
"""

import os
import subprocess

import pytest


CAPTURES = (
    ("quic-stream-ordered.pcap", 51000),
    ("quic-stream-out-of-order.pcap", 51001),
    ("quic-stream-retrans.pcap", 51002),
)

STREAMS = {
    0: (False, b"".join(b"alpha-%02d " % i for i in range(20))),
    4: (False, b"".join(b"bravo-%02d " % i for i in range(20))),
    3: (True, b"".join(b"charlie-%02d " % i for i in range(20))),
}

KEY_FILE = "quic-stream-reassembly.keys"
DECODE_ARGS = ("-d", "udp.port==4433,quic")


@pytest.fixture
def key_log(dirs):
    return os.path.join(dirs.key_dir, KEY_FILE)


class TestQuicStreamReassembly:
    @staticmethod
    def run_tshark(cmd_tshark, capture_file, test_env, key_log, capture_name,
                   *extra_args, passes=()):
        return subprocess.check_output(
            [cmd_tshark, *passes,
             "-r", capture_file(capture_name),
             "-o", "tls.keylog_file: " + key_log,
             *DECODE_ARGS, *extra_args],
            env=test_env,
            stderr=subprocess.DEVNULL,
        )

    @classmethod
    def follow_raw(cls, cmd_tshark, capture_file, test_env, key_log,
                   capture_name, stream_id, passes=()):
        """Return ``(client_bytes, server_bytes)`` from Follow QUIC raw."""
        output = cls.run_tshark(
            cmd_tshark, capture_file, test_env, key_log, capture_name,
            "-qz", "follow,quic,raw,0,%d" % stream_id,
            passes=passes,
        )

        client_data = bytearray()
        server_data = bytearray()
        for line in output.splitlines():
            is_server = line.startswith(b"\t")
            line = line.strip()
            if not line:
                continue
            try:
                chunk = bytes.fromhex(line.decode("ascii"))
            except ValueError:
                # Header, node, and separator lines are not hex chunks.
                continue
            if is_server:
                server_data.extend(chunk)
            else:
                client_data.extend(chunk)
        return bytes(client_data), bytes(server_data)

    @pytest.mark.parametrize("capture_name,client_port", CAPTURES)
    def test_connection_tracking(self, cmd_tshark, capture_file, test_env,
                                 key_log, capture_name, client_port):
        rows = self.run_tshark(
            cmd_tshark, capture_file, test_env, key_log, capture_name,
            "-Y", "quic.connection.number",
            "-Tfields",
            "-e", "quic.connection.number",
            "-e", "udp.srcport",
            "-e", "udp.dstport",
        ).decode().splitlines()

        assert rows
        assert {row.split("\t", 1)[0] for row in rows} == {"0"}

        ports = set()
        for row in rows:
            fields = row.split("\t")
            ports.update(fields[1:3])
        assert str(client_port) in ports
        assert "4433" in ports

        experts = self.run_tshark(
            cmd_tshark, capture_file, test_env, key_log, capture_name,
            "-Y", "_ws.malformed || _ws.expert.severity >= 0x00800000",
            "-Tfields", "-e", "frame.number",
        ).decode().splitlines()
        assert experts == []

    @pytest.mark.parametrize("capture_name,client_port", CAPTURES)
    def test_multi_stream_reassembly(self, cmd_tshark, capture_file, test_env,
                                     key_log, capture_name, client_port):
        for stream_id, (from_server, expected) in STREAMS.items():
            client_data, server_data = self.follow_raw(
                cmd_tshark, capture_file, test_env, key_log,
                capture_name, stream_id)
            reassembled = server_data if from_server else client_data
            assert reassembled == expected, (
                "stream %d in %s was not reassembled"
                % (stream_id, capture_name))

    def test_out_of_order_offsets(self, cmd_tshark, capture_file, test_env,
                                  key_log):
        output = self.run_tshark(
            cmd_tshark, capture_file, test_env, key_log,
            "quic-stream-out-of-order.pcap",
            "-Y", "quic.stream.stream_id == 0 && quic.stream.offset",
            "-Tfields", "-e", "quic.stream.offset",
        ).decode().splitlines()
        offsets = [int(line) for line in output if line]

        assert len(offsets) > 3
        assert offsets[1:] != sorted(offsets[1:])

    def test_retransmission_dedup(self, cmd_tshark, capture_file, test_env,
                                  key_log):
        output = self.run_tshark(
            cmd_tshark, capture_file, test_env, key_log,
            "quic-stream-retrans.pcap",
            "-Y", "quic.stream.stream_id == 0",
            "-Tfields", "-e", "quic.stream.offset",
        ).decode().splitlines()
        offsets = [int(line) if line else 0 for line in output]

        assert len(offsets) != len(set(offsets))
        client_data, _ = self.follow_raw(
            cmd_tshark, capture_file, test_env, key_log,
            "quic-stream-retrans.pcap", 0)
        assert client_data == STREAMS[0][1]

    @pytest.mark.parametrize("capture_name,client_port", CAPTURES)
    def test_two_pass_output_matches(self, cmd_tshark, capture_file, test_env,
                                    key_log, capture_name, client_port):
        for stream_id in STREAMS:
            one_pass = self.follow_raw(
                cmd_tshark, capture_file, test_env, key_log,
                capture_name, stream_id)
            two_pass = self.follow_raw(
                cmd_tshark, capture_file, test_env, key_log,
                capture_name, stream_id, passes=("-2",))
            assert one_pass == two_pass
